// 取某场景下的角色变体（找不到则返回 undefined）
export function getRoleVariant(
  scene: Scene,
  variantId?: string | null,
): RoleVariant | undefined {
  if (!variantId) return undefined;
  return ROLE_VARIANTS[scene].find((v) => v.id === variantId);
}
